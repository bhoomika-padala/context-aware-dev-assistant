def add(a, b):
    """Return the sum of a and b.

    Simple utility function that adds two numbers and returns the result.
    It works with any types supporting the ``+`` operator.
    """
    return a + b

def add_three(a, b, c):
    """Return the sum of three numbers.

    Simple utility function that adds three numbers and returns the result.
    It works with any types supporting the ``+`` operator.
    """
    return a + b + c
